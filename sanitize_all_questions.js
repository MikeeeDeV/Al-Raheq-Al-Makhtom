const filePaths = [
  './al_raheeq_al_makhtum_quiz_1200.json',
  './public/questions.json'
];

filePaths.forEach(filePath => {
  if (fs.existsSync(filePath)) {
    const raw = fs.readFileSync(filePath, 'utf8');
    const data = JSON.parse(raw);

    for (const secKey of Object.keys(data.sections)) {
      const sec = data.sections[secKey];
      const pool = trueFalseStatements[secKey] || trueFalseStatements['section_1'];

      sec.true_false = sec.true_false.map((q, idx) => {
        // Check if question has generic number prefix like "عبارة سيرة نبوية رقم 17..."
        const isGeneric = q.question.includes('عبارة') || q.question.includes('سيرة نبوية رقم') || q.question.includes('سؤال توثيقي رقم') || q.question.includes('تتعلق بأحداث');

        if (isGeneric) {
          const item = pool[idx % pool.length];
          return {
            ...q,
            question: item.q,
            options: ["صواب", "خطأ"],
            correct_answer: item.c,
            explanation: item.e
          };
        }

        // Clean any remaining leading numbers or "سيرة نبوية رقم X"
        let cleanText = q.question.replace(/(عبارة|سيرة نبوية|سؤال سيرة نبوية|سؤال توثيقي)\s*(رقم)?\s*\d*\s*(تتعلق بـ|تتعلق بأحداث|في)?/g, '').trim();
        if (!cleanText || cleanText.length < 5) {
          const item = pool[idx % pool.length];
          cleanText = item.q;
        }

        return {
          ...q,
          question: cleanText,
          options: ["صواب", "خطأ"],
          correct_answer: q.correct_answer || "صواب"
        };
      });

      // Also clean MCQ questions from any leading number prefixes
      sec.mcq = sec.mcq.map((q) => {
        let cleanText = q.question.replace(/(سؤال توثيقي|سؤال سيرة نبوية|سيرة نبوية)\s*(رقم)?\s*\d*\s*(في|حول)?/g, '').trim();
        if (!cleanText || cleanText.length < 5) {
          cleanText = `مسألة وتوثيق في معالم السيرة النبوية الشريفة`;
        }
        return {
          ...q,
          question: cleanText
        };
      });
    }

    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Sanitized all generic question prefixes in ${filePath}`);
  }
});
